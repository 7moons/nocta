export function builtInTheme(id: string) {
  return BUILT_IN_THEMES.find((theme) => theme.id === id);
}

// Fallback values for tokens missing from an imported or older custom theme.
export function defaultThemeFor(scheme: Theme["scheme"]) {
  return builtInTheme(scheme === "light" ? "nocta-light" : DEFAULT_THEME_ID)!;
}
